import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 2036 }, colorScheme: 'light' });
await page.goto('file://' + process.cwd() + '/brand/drafts/guide-print.html', { waitUntil: 'networkidle' });
await page.evaluate(() => document.fonts.ready);
await page.waitForTimeout(1500);
const bad = await page.evaluate(() => [...document.fonts].filter(f => f.status === 'error').map(f => f.family));
console.log('font errors', bad);
await page.emulateMedia({ media: 'screen' });
await page.pdf({ path: 'brand/drafts/The-Morning-Round-Brand-Guide.pdf', width: '1440px', height: '2036px', printBackground: true, margin: { top: '0', bottom: '0', left: '0', right: '0' } });
await browser.close();
if (bad.length) process.exitCode = 1;
